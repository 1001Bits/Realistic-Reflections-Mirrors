	void Result(MultiMirrorPolicy::Identity id, std::uint64_t source, bool attempted,
		bool success, const char* failure, std::uint64_t cpu, std::uint32_t width) noexcept
	{
		if (!MirrorFleetPolicy::enabled.load(std::memory_order_relaxed)) return;
		if (success) publications.fetch_add(1, std::memory_order_relaxed);
		std::scoped_lock lock(mutex); fleet.Result(id, source, Now(), attempted, success, failure, cpu, width);
	}
