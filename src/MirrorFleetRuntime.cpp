	void Report(std::uint64_t source, std::uint64_t bytes,
		const CapturePoolDiagnostics& targetPool) noexcept
	{
		if (!MirrorFleetPolicy::enabled.load(std::memory_order_relaxed)) return;
		const auto now = Now();
		if (!reportTime) {
			std::scoped_lock lock(mutex);
			reportTime = now; reportSource = source;
			(void)presentTiming.Take(); previousGPU = timer.Read();
			return;
		}
		if (now - reportTime < 5'000'000) return;
		try {
			std::scoped_lock lock(mutex);
			const double seconds = static_cast<double>(now - reportTime) / 1'000'000.0;
			const auto gpu = timer.Read();
			const auto count = gpu.samples - previousGPU.samples;
			const auto present = presentTiming.Take();
			logger::info("[MOS][Fleet] windowSeconds={:.3f} sourceFrames={} presentIntervals={} presentAvailable={} presentAvgMs={:.3f} presentMaxMs={:.3f} presentP50Ms={:.3f} presentP95Ms={:.3f} presentP99Ms={:.3f} gpuSamples={} gpuBatchAvgMs={:.3f} gpuInvalid={} gpuSaturated={} retained={} logicalBytes={} colorAllocations={} depthAllocations={} resolution={} refreshHz={} dynamicResolution={} visibleMirrors={} manualResolution={} presentPercentilesAvailable={} gpuFaulted={} gpuRejected={} windowEndUs={} adaptiveResolution={} adaptiveRefreshHz={} displayHz={}",
				seconds, source >= reportSource ? source - reportSource : 0, present.intervals, presentHookInstalled.load() && present.intervals != 0,
				present.average, present.maximum, present.p50, present.p95, present.p99, count,
				count ? (gpu.totalMs - previousGPU.totalMs) / count : 0.0, gpu.invalid, gpu.saturated,
				fleet.Entries().size(), bytes, colourAllocations, depthAllocations, frameQuality.resolution, MirrorFleetPolicy::refreshHz.load(),
				frameQuality.dynamic, frameQuality.visibleMirrors, frameQuality.manualResolution, present.percentilesAvailable, gpuFaulted, gpu.rejected, now, MirrorFleetPolicy::adaptiveResolution.load(),
				MirrorFleetPolicy::adaptiveRefreshHz.load(), displayHz.load(std::memory_order_relaxed));
			// Fixed-size counters are updated only on resize/reuse/eviction. Emit
			// changed shapes here, never log or allocate strings at texture creation.
			static CapturePoolDiagnostics previousPool{};
			for (std::size_t i = 0; i < targetPool.size(); ++i) {
				const auto& current = targetPool[i];
				const auto& before = previousPool[i];
				if (current == before) continue;
				logger::info("[MOS][TargetPool] size={}x{} allocations={} reuseHits={} evictions={} failures={} allocationTotalMs={:.3f} allocationLifetimeMaxMs={:.3f} windowAllocations={} windowAllocationMs={:.3f} windowEndUs={}",
					current.width, current.height, current.allocations, current.reuseHits, current.evictions,
					current.failures, current.allocationMicroseconds / 1000.0, current.maximumAllocationMicroseconds / 1000.0,
					current.allocations - before.allocations, (current.allocationMicroseconds - before.allocationMicroseconds) / 1000.0, now);
			}
			previousPool = targetPool;
			const auto depthStorage = HandMirrorPhysicalClipDepth::GetDiagnostics();
			logger::info("[MOS][DepthStorage] created={} storageReuses={} evictions={} residentBytes={} faults={} windowEndUs={}",
				depthStorage.resourceCreations, depthStorage.storageReuses, depthStorage.storageEvictions,
				depthStorage.storageBytes, depthStorage.faults, now);
			if (PhaseTimingEnabled()) {
				constexpr std::array names{"worldShadow", "playerShadow", "standing", "hand", "other"};
				for (std::size_t i = 0; i < names.size(); ++i) {
					const auto& current = gpu.phases[i]; const auto& before = previousGPU.phases[i];
					const auto samples = current.samples - before.samples;
					const auto cpuSamples = current.cpuSamples - before.cpuSamples;
					logger::info("[MOS][PhaseTiming] phase={} windowSeconds={:.3f} gpuSamples={} gpuTotalMs={:.3f} gpuAvgMs={:.3f} gpuInvalid={} cpuSamples={} cpuTotalMs={:.3f} cpuAvgMs={:.3f} rejected={} saturated={} queryPairs={} windowEndUs={}",
						names[i], seconds, samples, current.totalMs - before.totalMs,
						samples ? (current.totalMs - before.totalMs) / samples : 0.0, current.invalid,
						cpuSamples, current.cpuTotalMs - before.cpuTotalMs,
						cpuSamples ? (current.cpuTotalMs - before.cpuTotalMs) / cpuSamples : 0.0,
						gpu.phaseRejected, gpu.phaseSaturated, gpu.phaseQueryPairs, now);
				}
			}
			for (const auto& [id, e] : fleet.Entries()) {
				logger::info("[MOS][FleetRef] ref={:08X} generation={} visible={} planned={} attempts={} successes={} failures={} consecutiveFailures={} lastAttempt={} lastSuccess={} ageFrames={} firstFailure={} firstFailureSource={} lastFailure={} lastFailureSource={} retryDueUs={} cpuUs={} width={} resumePresentations={}",
					id, e.identity.generation, e.visible, e.planned, e.attempts, e.successes, e.failures, e.consecutiveFailures,
					e.lastAttemptSource, e.lastSuccessSource, e.lastSuccessSource && source >= e.lastSuccessSource ? source - e.lastSuccessSource : 0,
					e.firstFailure, e.firstFailureSource, e.lastFailure, e.lastFailureSource, e.clock.started && e.clock.next > now ? e.clock.next - now : 0, e.cpuMicroseconds, e.width, e.resumePresentations);
			}
			previousGPU = gpu; reportSource = source; reportTime = now;
		} catch (...) {}
	}
