	void BeginFrame(ID3D11Device*, ID3D11DeviceContext* context, std::uint64_t source) noexcept
	{
		MirrorPrivateShadow::ObserveSourceTime(source, Now());
		if (!MirrorFleetPolicy::enabled.load(std::memory_order_relaxed) && !MirrorPerformance::Requested()) return;
		TryPresentHook();
		ObserveAdaptiveQuality(source, Now());
		__try { if (!gpuFaulted) timer.Poll(context); }
		__except (EXCEPTION_EXECUTE_HANDLER) { gpuFaulted = true; }
	}
	bool ResumeImage(MultiMirrorPolicy::Identity id, std::uint64_t source,
		std::uint64_t captureSource, std::uint64_t capture) noexcept
	{
		if (!MirrorFleetPolicy::enabled.load(std::memory_order_relaxed)) return false;
		std::scoped_lock lock(mutex); return fleet.ResumeImage(id, source, captureSource, capture);
	}
	void BeginGPU(ID3D11Device* device, ID3D11DeviceContext* context) noexcept
	{
		__try {
			if (!gpuFaulted && MirrorFleetPolicy::enabled.load(std::memory_order_relaxed))
				(void)timer.Begin(device, context, PhaseTimingEnabled());
		} __except (EXCEPTION_EXECUTE_HANDLER) { gpuFaulted = true; }
	}
