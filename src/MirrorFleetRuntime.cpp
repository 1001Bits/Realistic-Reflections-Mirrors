	{
		__try {
			if (!gpuFaulted && MirrorFleetPolicy::enabled.load(std::memory_order_relaxed)) timer.End(context);
		} __except (EXCEPTION_EXECUTE_HANDLER) { gpuFaulted = true; }
	}
